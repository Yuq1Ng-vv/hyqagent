"""scanner/hypothesis.py — LLM-powered vulnerability hypothesis generation.

Generates structured vulnerability hypotheses from Phase 2 annotated paths
that the deterministic scanner cannot confirm or reject.

Input paths by label:
- HEURISTIC_SINK — "This looks dangerous but I don't know what vulnerability it is"
- EXPOSED_NO_SOURCE — "This endpoint takes user input but I don't trace it"
- UNCOVERED_SINK — "This sink is reachable but no rule covers it"
- CONDITIONAL_SANITIZED — "There's a sanitizer but it might be bypassable"

For each path, the generator:
1. Builds a CPG-sliced code context (only the relevant code, not the full file)
2. Routes to the appropriate model tier via :class:`ModelRouter`
3. Produces structured :class:`Hypothesis` objects via Anthropic tool_use

When a :class:`NudgeLoop` is provided via *nudge_loop*, each LLM call is
wrapped in a multi-turn loop that prevents premature termination (empty
hypotheses, text-only responses, low-confidence submissions).  The nudge
system is adapted from AutoCVE — see :mod:`hyqagent.scanner.nudge` and
``docs/AUTOCVE-RESEARCH.md`` for attribution.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

import structlog

if TYPE_CHECKING:
    from hyqagent.cpg.query import CPGQuery, GraphPath
    from hyqagent.cpg.types import BlindSpot
    from hyqagent.core.protocols import LlmProvider
    from hyqagent.models.router import ModelRouter
    from hyqagent.scanner.nudge import NudgeLoop

logger = structlog.get_logger(__name__)


# ── Hypothesis dataclass ─────────────────────────────────────────────────────


@dataclass
class Hypothesis:
    """A structured vulnerability hypothesis generated by an LLM.

    This is the raw LLM output — not yet validated. Feed to
    :class:`Validator` for L1 and L2 verification.
    """

    id: str
    vuln_type: str  # e.g. "sql_injection", "xss", "idor"
    cwe_id: str  # e.g. "CWE-89"
    severity: str  # critical | high | medium | low
    confidence: float  # 0.0 — 1.0 (LLM self-assessment)
    title: str
    description: str
    source_location: str  # "file.py:42"
    sink_location: str  # "file.py:128"
    evidence: str  # quoted code snippet
    reasoning: str  # LLM's explanation
    remediation: str = ""
    metadata: dict[str, Any] = field(default_factory=dict)

    @property
    def stable_key(self) -> str:
        """Deterministic identity for cross-round deduplication.

        Based on source_location + sink_location + vuln_type —
        the same vulnerability found in different rounds will have
        the same stable_key regardless of random ``id``.
        """
        return f"{self.source_location}|{self.sink_location}|{self.vuln_type}"


