"""cpg/coverage.py — Coverage tracker and blind-spot manifest generator.

Provides quantitative visibility into what the analyser covered and what it
didn't — a capability that no mainstream SAST tool currently offers out of
the box.

All computation is **zero-LLM** — pure CPG graph statistics.

Architecture: The blind-spot manifest is a critical input to Phase 3 LLM.
If a detection dimension is NOT in the manifest, the LLM won't know to
check for it. The manifest combines:
  * Hardcoded structural blind spots (always-present gaps in CPG modeling)
  * Per-scan category gaps (taint categories not triggered)
  * Per-scan endpoint gaps (HTTP endpoints without source coverage)
  * External coverage manifest (items from phase12_coverage_tracking.json
    that require Phase 3 LLM — loaded via :meth:`load_phase3_manifest`)
"""

