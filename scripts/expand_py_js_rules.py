# YAML generation
# ═══════════════════════════════════════════════════════════════════════════


def _yaml_str(s: str) -> str:
    """Return properly quoted YAML string. Always quotes for safety."""
    if not s:
        return "''"
    # Use single quotes for all strings that don't contain single quotes
    if "'" not in s:
        return f"'{s}'"
    # String contains single quotes: use double-quoted YAML, escape " and \
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _yaml_list(items: list[str], indent: int = 6) -> str:
    """Render deduplicated, sorted YAML list."""
    seen: set[str] = set()
    unique: list[str] = []
    for item in items:
        if item not in seen:
            seen.add(item)
            unique.append(item)
    unique.sort()
    prefix = " " * indent
    return "\n".join(f"{prefix}- {_yaml_str(item)}" for item in unique)


def _generate_section(
    lang_display: str,
    lang_key: str,
    categories: list[str],
    sources: dict[str, list[str]],
    sinks: dict[str, list[str]],
    sanitizers: dict[str, list[str]],
) -> str:
    """Generate complete language YAML section."""
    lines = []
    lines.append(f"# {'═' * 75}")
    lines.append(f"# {lang_display}")
    lines.append(f"# {'═' * 75}")
    lines.append("")
    lines.append(f"{lang_key}:")

    lines.append("  sources:")
    lines.append("    # ── Framework-agnostic HTTP input (variable-agnostic dot-prefixed) ──")
    for cat in categories:
        lines.append(f"    {cat}:")
        pats = sources.get(cat, [])
        if pats:
            lines.append(_yaml_list(pats, 6))
        else:
            lines.append("      []  # static detection — no taint source needed")

    lines.append("")
    lines.append("  sinks:")
    for cat in categories:
        lines.append(f"    {cat}:")
        pats = sinks.get(cat, [])
        if pats:
            lines.append(_yaml_list(pats, 6))
        else:
            lines.append("      []")

    lines.append("")
    lines.append("  sanitizers:")
    for cat in categories:
        lines.append(f"    {cat}:")
        pats = sanitizers.get(cat, [])
        if pats:
            lines.append(_yaml_list(pats, 6))
        else:
            lines.append("      []")

    return "\n".join(lines)


def main() -> None:
    import shutil

    with open(RULES_PATH, encoding="utf-8") as f:
        content = f.read()

    lines = content.splitlines(keepends=True)

    # Find section boundaries
    py_header = js_header = java_line = None
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("# Python") and py_header is None:
            py_header = i
        elif stripped.startswith("# JavaScript") and js_header is None:
            js_header = i
        elif stripped.startswith("java:") and java_line is None:
            java_line = i

    if py_header is None or js_header is None or java_line is None:
        print(
            f"ERROR: Could not find section boundaries: py={py_header}, js={js_header}, java={java_line}"
        )
        sys.exit(1)

    header = "".join(lines[:py_header])
    java_section = "".join(lines[java_line:]).rstrip("\n")

    py_section = _generate_section(
        "Python", "python", PY_CATEGORIES, PY_SOURCES, PY_SINKS, PY_SANITIZERS
    )
    js_section = _generate_section(
        "JavaScript / TypeScript", "javascript", JS_CATEGORIES, JS_SOURCES, JS_SINKS, JS_SANITIZERS
    )

    output = header + py_section + "\n\n" + js_section + "\n\n" + java_section + "\n"

    if "--diff" in sys.argv:
        import difflib

        diff = difflib.unified_diff(
            content.splitlines(keepends=True),
            output.splitlines(keepends=True),
            fromfile="taint_rules.yaml (original)",
            tofile="taint_rules.yaml (expanded)",
        )
        sys.stdout.writelines(diff)
        return

    backup_path = RULES_PATH.with_suffix(".yaml.bak")
    shutil.copy2(RULES_PATH, backup_path)

    with open(RULES_PATH, "w", encoding="utf-8") as f:
        f.write(output)

    print(f"✅ Expanded {RULES_PATH}")
    print(f"   Backup: {backup_path}")

    for lang, cats, srcs, snks, sans in [
        ("python", PY_CATEGORIES, PY_SOURCES, PY_SINKS, PY_SANITIZERS),
        ("javascript", JS_CATEGORIES, JS_SOURCES, JS_SINKS, JS_SANITIZERS),
    ]:
        n_src = sum(len(v) for v in srcs.values())
        n_snk = sum(len(v) for v in snks.values())
        n_san = sum(len(v) for v in sans.values())
        print(
            f"   {lang}: {len(cats)} categories → "
            f"{n_src} sources, {n_snk} sinks, {n_san} sanitizers "
            f"({n_src + n_snk + n_san} total)"
        )


if __name__ == "__main__":
    main()
